#!/usr/bin/env python3
"""Render both Pages languages from one HTML template and small locale files."""
import argparse
import html
import json
from pathlib import Path
from string import Template

ROOT = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
template = Template((ROOT / 'web/page.html').read_text())
for code, prefix, suffix in (('zh', './', ''), ('en', '../', 'en/')):
    content = json.loads((ROOT / f'web/locales/{code}.json').read_text())
    canonical = 'https://qixuancao.github.io/sing-box-config-templates/' + suffix
    data = {
        '@context': 'https://schema.org', '@graph': [
            {'@type': 'SoftwareSourceCode', 'name': 'sing-box-config-templates',
             'description': content['description'], 'url': canonical,
             'codeRepository': 'https://github.com/qixuancao/sing-box-config-templates',
             'programmingLanguage': ['JavaScript', 'JSON'], 'runtimePlatform': 'Browser / Node.js 22+; sing-box 1.13 / 1.14',
             'license': 'https://github.com/qixuancao/sing-box-config-templates/blob/main/LICENSE'},
            {'@type': 'FAQPage', 'mainEntity': [
                {'@type': 'Question', 'name': q, 'acceptedAnswer': {'@type': 'Answer', 'text': a}}
                for q, a in content.pop('faq')]},
        ]}
    values = {key: html.escape(value, quote=True) for key, value in content.items()}
    values.update(prefix=prefix, canonical=canonical, home='./' if code == 'zh' else '../',
                  zh_href='./' if code == 'zh' else '../', en_href='./en/' if code == 'zh' else './',
                  zh_current='aria-current="page"' if code == 'zh' else '',
                  en_current='aria-current="page"' if code == 'en' else '',
                  structured_data=json.dumps(data, ensure_ascii=False).replace('<', '\\u003c'))
    result = '<!-- Generated by scripts/build-pages.py; edit web/page.html and web/locales/. -->\n' + template.substitute(values)
    target = ROOT / 'docs' / suffix / 'index.html'
    if args.check:
        if not target.is_file() or target.read_text() != result:
            raise SystemExit('Pages are stale; run python3 scripts/build-pages.py')
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(result)
print('Pages match the shared template and both locales.' if args.check else 'Built Chinese and English Pages.')
