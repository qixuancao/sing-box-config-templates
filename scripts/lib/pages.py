"""Render and validate the shared bilingual Pages site."""
import html
from html.parser import HTMLParser
import json
import re
from string import Template
import xml.etree.ElementTree as ET

from .common import ROOT, read_json, require

SITE = "https://qixuancao.github.io/sing-box-config-templates/"


def outputs(root=ROOT):
    template = Template((root / "web/page.html").read_text(encoding="utf-8"))
    result = {}
    for code, prefix, suffix in (("zh", "./", ""), ("en", "../", "en/")):
        content = read_json(root / f"web/locales/{code}.json")
        canonical = SITE + suffix
        data = {
            "@context": "https://schema.org", "@graph": [
                {"@type": "SoftwareSourceCode", "name": "sing-box-config-templates",
                 "description": content["description"], "url": canonical,
                 "codeRepository": "https://github.com/qixuancao/sing-box-config-templates",
                 "programmingLanguage": ["JavaScript", "JSON"], "runtimePlatform": "Browser / Node.js 22+; sing-box 1.13 / 1.14",
                 "license": "https://github.com/qixuancao/sing-box-config-templates/blob/main/LICENSE"},
                {"@type": "FAQPage", "mainEntity": [
                    {"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}}
                    for q, a in content.pop("faq")]},
            ]}
        values = {key: html.escape(value, quote=True) for key, value in content.items()}
        values.update(prefix=prefix, canonical=canonical, home="./" if code == "zh" else "../",
                      zh_href="./" if code == "zh" else "../", en_href="./en/" if code == "zh" else "./",
                      zh_current='aria-current="page"' if code == "zh" else "",
                      en_current='aria-current="page"' if code == "en" else "",
                      structured_data=json.dumps(data, ensure_ascii=False).replace("<", "\\u003c"))
        result[f"docs/{suffix}index.html"] = "<!-- Generated by scripts/build.py; edit web/page.html and web/locales/. -->\n" + template.substitute(values)
    return result


class PageInfo(HTMLParser):
    def __init__(self):
        super().__init__()
        self.title = ""
        self.in_title = False
        self.metas = []
        self.links = []
        self.scripts = []
        self.inline_scripts = []
        self.current_script = None
        self.lang = ""
        self.anchors = []
        self.element_ids = set()
        self.current_select = None
        self.core_versions = []
        self.has_viewport = False

    def handle_starttag(self, tag, attrs):
        attributes = dict(attrs)
        if tag == "html":
            self.lang = attributes.get("lang", "")
        elif tag == "title":
            self.in_title = True
        elif tag == "meta":
            self.metas.append(attributes)
            if attributes.get("name") == "viewport":
                self.has_viewport = True
        elif tag == "link":
            self.links.append(attributes)
        elif tag == "script":
            self.scripts.append(attributes)
            if "src" not in attributes:
                self.current_script = []
        elif tag == "a" and "href" in attributes:
            self.anchors.append(attributes["href"])
        elif tag in ("select", "input", "textarea", "button"):
            if "id" in attributes:
                self.element_ids.add(attributes["id"])
            if tag == "select":
                self.current_select = attributes.get("id")
        elif tag == "option" and self.current_select == "core":
            self.core_versions.append(attributes.get("value"))

    def handle_endtag(self, tag):
        if tag == "title":
            self.in_title = False
        elif tag == "select":
            self.current_select = None
        elif tag == "script" and self.current_script is not None:
            self.inline_scripts.append("".join(self.current_script))
            self.current_script = None

    def handle_data(self, data):
        if self.in_title:
            self.title += data
        if self.current_script is not None:
            self.current_script.append(data)


def check_page(path, *, root, lang, canonical, other_hreflang):
    text = path.read_text(encoding="utf-8")
    info = PageInfo()
    info.feed(text)

    def expect(condition, message):
        require(condition, f"{path.relative_to(root)}: {message}")

    def meta_ok(**attributes):
        return any(all(meta.get(key) == value for key, value in attributes.items()) for meta in info.metas)

    expect(info.lang == lang, f"lang must be {lang}")
    expect(info.title.strip(), "missing title")
    expect(info.has_viewport, "missing viewport")
    expect(meta_ok(name="description"), "missing meta description")
    description = next(meta.get("content", "") for meta in info.metas if meta.get("name") == "description")
    expect(len(description.strip()) >= 20, "meta description too short")
    expect([link.get("href") for link in info.links if link.get("rel") == "canonical"] == [canonical], "incorrect canonical URL")
    hreflangs = {link.get("hreflang"): link.get("href") for link in info.links if "hreflang" in link}
    expect({"zh-CN", "en"} <= set(hreflangs), "missing zh-CN/en hreflang")
    expect(hreflangs.get(other_hreflang[0]) == other_hreflang[1], "incorrect alternate language URL")
    expect(any(link.get("rel") == "sitemap" and "sitemap.xml" in link.get("href", "") for link in info.links), "missing sitemap link")
    for prop in ("og:title", "og:description", "og:url", "og:type", "og:locale"):
        expect(meta_ok(property=prop), f"missing {prop}")
    for name in ("twitter:card", "twitter:title", "twitter:description"):
        expect(meta_ok(name=name), f"missing {name}")
    for script in info.scripts:
        expect(not script.get("src", "").startswith(("http://", "https://", "//")), "external script")
    for analytics in ("google-analytics", "googletagmanager", "matomo", "umami", "plausible", "hotjar"):
        expect(analytics not in text.lower(), "analytics reference")

    expect(any(script.get("type") == "application/ld+json" for script in info.scripts), "missing JSON-LD")
    found_software = found_faq = False
    for raw in info.inline_scripts:
        if not raw.strip().startswith("{"):
            continue
        data = json.loads(raw)
        for node in data.get("@graph", [data]):
            if node.get("@type") == "SoftwareSourceCode":
                found_software = True
            if node.get("@type") == "FAQPage":
                found_faq = True
                expect(node.get("mainEntity"), "FAQ has no questions")
    expect(found_software and found_faq, "JSON-LD must include SoftwareSourceCode and FAQ")
    expect(info.core_versions == list(read_json(root / "modules/catalog.json")["versions"]), "core versions must match modules/catalog.json")
    for element in ("platform", "core", "scenario", "nodes-input", "nodes-file", "generate",
                    "download-json", "download-nodes", "copy-json", "clear", "json-preview", "out-path", "out-raw", "out-cmd"):
        expect(element in info.element_ids, f"missing generator element: {element}")
    module = next((script.get("src") for script in info.scripts if script.get("type") == "module"), None)
    expect(module and (path.parent / module).resolve() == (root / "docs/assets/app.mjs").resolve(), "must use the shared generator module")
    joined_js = "\n".join(source.read_text(encoding="utf-8") for source in sorted((root / "docs/assets").rglob("*.mjs")))
    for token in ("raw.githubusercontent.com", "generate.mjs", "URL.createObjectURL", "anchor.download", "sing-box.json"):
        expect(token in joined_js or token in text, f"missing generator output: {token}")
    for pattern in (r"\bfetch\s*\(", r"XMLHttpRequest", r"navigator\.sendBeacon", r"\bWebSocket\s*\(",
                    r"\blocalStorage\b", r"\bsessionStorage\b", r"\bindexedDB\b"):
        expect(not re.search(pattern, joined_js), "generator must not send or store node input")
    expect(meta_ok(**{"http-equiv": "Content-Security-Policy"}) and "connect-src 'none'" in text, "CSP must block runtime network requests")
    expect("占位" in text or "placeholder" in text.lower(), "must explain Raw JSON placeholders")
    expect("skip" in text.lower() or "跳到" in text, "missing keyboard skip link")
    styles = "\n".join((path.parent / link["href"]).read_text(encoding="utf-8") for link in info.links if link.get("rel") == "stylesheet")
    expect(":focus-visible" in styles, "missing focus style")
    expect("@media" in styles, "missing responsive CSS")
    for href in info.anchors:
        expect(href.startswith(("http", "#", "mailto:")) or href in ("./", "./en/", "../", "./sitemap.xml", "../sitemap.xml"), "unexpected site-internal link")
    return info


def check(root=ROOT):
    for name in ("docs/index.html", "docs/en/index.html", "docs/sitemap.xml", "docs/.nojekyll"):
        require((root / name).is_file(), f"Missing Pages file: {name}")
    zh = check_page(root / "docs/index.html", root=root, lang="zh-CN", canonical=SITE, other_hreflang=("en", SITE + "en/"))
    en = check_page(root / "docs/en/index.html", root=root, lang="en", canonical=SITE + "en/", other_hreflang=("zh-CN", SITE))
    require(zh.title.strip() != en.title.strip(), "Chinese and English titles must be independent")
    tree = ET.parse(root / "docs/sitemap.xml")
    locations = [node.text.strip() for node in tree.getroot().findall("s:url/s:loc", {"s": "http://www.sitemaps.org/schemas/sitemap/0.9"})]
    require(locations == [SITE, SITE + "en/"], "Incorrect sitemap locations")
    print("Pages passed: bilingual SEO, local generator, CSP and responsive styles.", flush=True)
