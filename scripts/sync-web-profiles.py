#!/usr/bin/env python3
"""Bundle public profiles for offline browser generation; --check detects drift."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
profiles = {}
for path in sorted((root / 'platforms').glob('*/*/*.json')):
    if path.parent.name not in ('1.13', '1.14'):
        raise SystemExit('Unexpected profile version')
    profiles[str(path.relative_to(root))] = json.loads(path.read_text())
if len(profiles) != 34:
    raise SystemExit('Expected 34 maintained platform profiles')
output = root / 'docs/assets/profiles.mjs'
content = '// Generated by scripts/sync-web-profiles.py; edit platforms/ sources.\nexport const PROFILES = ' + json.dumps(profiles, ensure_ascii=False, separators=(',', ':')) + ';\n'
if args.check:
    if not output.is_file() or output.read_text() != content:
        raise SystemExit('Browser profiles are stale; run python3 scripts/sync-web-profiles.py')
    print('Browser bundle matches all 34 public platform profiles.')
else:
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content)
    print('Bundled 34 public platform profiles.')
