#!/usr/bin/env python3
"""Bundle the manifest's public profiles for offline browser generation."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
catalog = json.loads((root / 'presets/catalog.json').read_text())
profiles = {}
for version in catalog['versions']:
    for platform, settings in catalog['platforms'].items():
        for scenario in settings['scenarios']:
            path = f'platforms/{platform}/{version}/{scenario}.json'
            profiles[path] = json.loads((root / path).read_text())
output = root / 'docs/assets/profiles.mjs'
content = '// Generated by scripts/sync-web-profiles.py; edit modules/ and presets/.\nexport const PROFILES = ' + json.dumps(dict(sorted(profiles.items())), ensure_ascii=False, separators=(',', ':')) + ';\n'
if args.check:
    if not output.is_file() or output.read_text() != content:
        raise SystemExit('Browser profiles are stale; run ./scripts/sync-platforms.sh')
    print(f'Browser bundle matches all {len(profiles)} public platform profiles.')
else:
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content)
    print(f'Bundled {len(profiles)} public platform profiles.')
